import { revalidatePage } from './revalidation.mjs'
import assert from 'node:assert/strict'

export async function expectToast(evaluate, until, type, message) {
  await until(() => evaluate(`[...document.querySelectorAll('[data-sonner-toast][data-type="${type}"]')].some(el => el.textContent.includes(${JSON.stringify(message)}))`), `${type}: ${message}`)
  assert.equal(await evaluate(`[...document.querySelectorAll('[data-sonner-toast]')].filter(el => el.textContent.includes(${JSON.stringify(message)})).length`), 1, 'one outcome toast per action')
}

export async function loadingFeedbackChecks({ send, navigate, click, fill, evaluate, waitText, until, delayList, failMutation, failMail, failLoad, requests }) {
  await navigate('/admin'); await waitText('Administration')
  assert.equal(await evaluate('document.querySelectorAll("[data-sonner-toast]").length'), 0)
  delayList()
  await evaluate(`document.querySelector('aside a[href="/admin/accounts"]').click()`)
  await until(() => evaluate('!!document.querySelector("main .skeleton-state-page")'), 'route Suspense skeleton inside shell')
  assert(await evaluate('!!document.querySelector(".app-topbar")'))
  await until(() => evaluate('!!document.querySelector(".skeleton-state-table")'), 'directory initial skeleton')
  assert(await evaluate('[...document.querySelectorAll(".skeleton")].every(el => el.getAttribute("aria-hidden") === "true")'))
  assert.equal(await evaluate('document.querySelector(".skeleton-state-table").getAttribute("aria-busy")'), 'true')
  await send('Emulation.setEmulatedMedia', { features: [{ name:'prefers-reduced-motion', value:'reduce' }, {name:'prefers-color-scheme',value:'dark'}] })
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".skeleton")).animationName'), 'none')
  await send('Emulation.setDeviceMetricsOverride',{width:320,height:844,deviceScaleFactor:1,mobile:true})
  assert(await evaluate('document.documentElement.scrollWidth <= innerWidth'))
  await waitText('Employee Eve')
  assert.equal(await evaluate('document.querySelectorAll(".skeleton-state").length'),0)
  delayList()
  await revalidatePage(evaluate)
  assert(await evaluate('!!document.querySelector("[data-account-id]")'))
  assert.equal(await evaluate('document.querySelectorAll(".skeleton-state").length'),0)
  await until(() => evaluate('!document.querySelector(".refresh-status")'), 'refresh complete')
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false})
  await fill('[aria-label="Search accounts"]','no such feedback identity')
  await waitText('No matching accounts')
  assert.equal(await evaluate('document.querySelectorAll(".skeleton-state").length'),0)
  failLoad(true); delayList()
  await navigate('/admin/accounts')
  await until(() => evaluate('!!document.querySelector(".skeleton-state-table")'), 'failed-load starts with skeleton')
  await waitText('Administration temporarily unavailable')
  assert.equal(await evaluate('document.querySelectorAll(".skeleton-state").length'),0)
  failLoad(false)
  await click('Try again'); await waitText('Employee Eve')
  const create = async email => {
    await click('Create account')
    await fill('[aria-label="Account display name"]','Feedback Person')
    await fill('[aria-label="Account job title"]','Analyst')
    await fill('[aria-label="Account email"]',email)
    await fill('[aria-label="Account role"]','EMPLOYEE')
  }
  await create('feedback1@example.test')
  failMutation()
  await click('Confirm')
  await expectToast(evaluate,until,'error','Record unavailable or forbidden')
  await click('Cancel')
  await create('feedback2@example.test')
  const before = requests.filter(r => r === 'POST /auth/accounts').length
  await evaluate('document.querySelector("dialog form").requestSubmit(); document.querySelector("dialog form").requestSubmit()')
  await expectToast(evaluate,until,'success','Account created')
  assert.equal(requests.filter(r => r === 'POST /auth/accounts').length,before+1)
  await navigate('/admin/accounts'); await waitText('Employee Eve')
  await create('feedback3@example.test'); failMail(); await click('Confirm')
  await expectToast(evaluate,until,'warning','Account created, but activation email delivery failed')
  assert.equal(await evaluate('document.querySelectorAll("[data-sonner-toast][data-type=success]").length'),0)
  await navigate('/admin/ticket-configuration'); await waitText('Ticket configuration')
  await click('Create category'); await fill('[aria-label="Configuration name"]','Feedback category'); await click('Confirm')
  await expectToast(evaluate,until,'success','Ticket configuration updated')
  await click('Create category'); await fill('[aria-label="Configuration name"]','Rejected category'); failMutation(); await click('Confirm')
  await expectToast(evaluate,until,'error','Record unavailable or forbidden')
  await click('Cancel')
  await navigate('/profile'); await waitText('Change password')
  await fill('input[autocomplete=current-password]','CurrentPassword123!')
  await fill('input[autocomplete=new-password]','NewPassword123!')
  await fill('input[autocomplete=new-password]:last-of-type','NewPassword123!')
  // Inputs live in separate labels; use the final input for confirmation.
  await evaluate('document.querySelectorAll("input[autocomplete=new-password]")[1].value = "Mismatch"')
  await fill('.security-form label:last-of-type input','Mismatch')
  await click('Change password')
  await expectToast(evaluate,until,'warning','Check the password requirements')
  assert(await evaluate('document.querySelector(".security-form").textContent.includes("matching passwords")'))
  const warningDark = await evaluate('getComputedStyle(document.querySelector("[data-sonner-toast][data-type=warning]")).backgroundColor')
  await send('Emulation.setEmulatedMedia',{features:[{name:'prefers-color-scheme',value:'light'}]})
  await until(() => evaluate(`getComputedStyle(document.querySelector('[data-sonner-toast][data-type=warning]')).backgroundColor !== ${JSON.stringify(warningDark)}`),'warning theme colors update')
  await send('Emulation.setEmulatedMedia',{features:[]})
  console.log('PASS: route/list skeletons, retained refresh, reduced motion, dark/mobile, account/config outcomes, partial-delivery warning, inline validation and duplicate-submit guard')
}
