import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'
import { writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

export async function manualPolish({ send, evaluate, navigate, waitText, click, fill, until, requests, mutations, accounts, browserErrors, delayList, delayCatalog, failMailAction, setIdentity }) {
  const key = async (key, code, value, modifiers = 0) => {
    for (const type of ['keyDown', 'keyUp']) await send('Input.dispatchKeyEvent', { type, key, code, windowsVirtualKeyCode: value, modifiers, ...(type === 'keyDown' && key === 'Enter' ? { text: '\r' } : {}) })
  }
  const escape = () => key('Escape', 'Escape', 27)
  const viewport = (width, height = 900, scale = 1) => send('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: scale, mobile: false })
  const screenshot = async name => {
    const result = await send('Page.captureScreenshot', { format: 'png' })
    writeFileSync(join(tmpdir(), `eds-manual-${name}.png`), Buffer.from(result.data, 'base64'))
  }
  const fits = async () => assert(await evaluate('document.documentElement.scrollWidth <= innerWidth'), 'No horizontal overflow')
  await navigate('/admin')
  await waitText('Kino Service Desk')
  await send('Page.bringToFront')
  assert.equal(await evaluate('document.title'), 'Kino Service Desk')
  assert(!/northstar|enterprise service desk/i.test(await evaluate('document.body.innerText')))
  await evaluate(`document.querySelector('[aria-label="Notifications"]').focus()`)
  await key('Enter', 'Enter', 13)
  await waitText('No notifications yet')
  assert(await evaluate('!!document.querySelector(".notification-empty svg")'))
  await screenshot('notifications-light')
  await escape()
  assert.equal(await evaluate('document.activeElement.getAttribute("aria-label")'), 'Notifications')

  await evaluate('document.querySelector(".topbar-profile").focus()')
  await key('Enter', 'Enter', 13)
  await waitText('Change password')
  await click('Back')
  await until(() => evaluate('location.pathname === "/admin"'), 'profile returns in-app')
  await navigate('/profile')
  await waitText('Back to workspace')
  await click('Back to workspace')
  await waitText("Manage your service desk's people and configuration.")
  assert.equal(await evaluate('location.pathname'), '/admin')
  setIdentity('Display Identity')
  await navigate('/admin')
  await waitText('Display Identity')
  assert.equal(await evaluate('document.querySelector(".topbar-profile-name").textContent'), 'Display Identity')
  for (const [name, initial] of [['  Hasan Kanaan ', 'H'], ['\u00c9lodie Martin', '\u00c9'], ['E\u0301lodie', 'E\u0301'], ['\u{1f469}\u200d\u{1f4bb} Support', '\u{1f469}\u200d\u{1f4bb}'], ['   ', '']]) {
    setIdentity(name)
    await navigate('/profile')
    await waitText('Change password')
    assert.equal(await evaluate('document.querySelector(".topbar-profile .avatar").textContent'), initial)
    assert.equal(await evaluate('document.querySelector(".profile-header .avatar").textContent'), initial)
    if (!initial) assert(await evaluate('!!document.querySelector(".topbar-profile .avatar svg")'))
    assert(!/Username/i.test(await evaluate('document.querySelector("main").innerText')))
  }
  await evaluate(`document.querySelector('aside a[href="/settings"]').focus()`)
  await key('Enter', 'Enter', 13)
  await until(() => evaluate('location.pathname === "/settings"'), 'Settings keyboard navigation')
  assert(await evaluate(`document.querySelector('aside a[href="/settings"]').getAttribute('aria-current') === 'page'`))
  assert.equal(await evaluate(`document.querySelectorAll('.sidebar-account .avatar, .sidebar-account a[href="/profile"]').length`), 0)
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await evaluate(`document.querySelector('[aria-label="Open navigation"]').click()`)
  await until(() => evaluate('!!document.querySelector(".navigation-drawer[open]")'), 'mobile navigation')
  await evaluate(`document.querySelector('.navigation-drawer a[href="/settings"]').click()`)
  await until(() => evaluate('!document.querySelector(".navigation-drawer[open]")'), 'mobile Settings closes drawer')
  await fits()
  await viewport(1440)
  setIdentity('Admin user')
  await navigate('/admin/accounts')
  await waitText('Employee Eve')
  assert.equal(await evaluate('document.querySelector(".topbar-profile-name").textContent'), 'Admin user')

  await evaluate('window.savedRow = document.querySelector("[data-account-id]"); void 0')
  const count = requests.filter(r => r === 'GET /users').length
  delayList()
  await evaluate(`[...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Refresh accounts').click()`)
  await waitText('Refreshing')
  assert(await evaluate('window.savedRow.isConnected && !!window.savedRow.closest("[inert]")'), 'Refresh retains row and disables stale actions')
  await evaluate(`for (let i=0;i<4;i++) [...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Refresh accounts').click()`)
  await delay(1100)
  assert.equal(requests.filter(r => r === 'GET /users').length, count + 1)
  assert(await evaluate('window.savedRow.isConnected'), 'Refresh keeps DOM identity')

  await evaluate(`[...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Create account').focus()`)
  await click('Create account')
  assert(await evaluate('document.querySelector(".form-drawer").open && document.body.style.overflow === "hidden"'))
  for (let i=0;i<18;i++) {
    await key('Tab', 'Tab', 9)
    assert(await evaluate('!!document.activeElement.closest(".form-drawer")'), 'Drawer traps focus')
  }
  await evaluate(`document.querySelector('[aria-label="Close dialog"]').focus()`)
  await key('Tab', 'Tab', 9, 8)
  assert.equal(await evaluate('document.activeElement.textContent.trim()'), 'Cancel')
  await escape()
  assert.equal(await evaluate('document.activeElement.textContent.trim()'), 'Create account')
  assert.equal(await evaluate('document.body.style.overflow'), '')
  await click('Create account')
  for (const type of ['mousePressed', 'mouseReleased']) await send('Input.dispatchMouseEvent', { type, x: 10, y: 250, button: 'left', clickCount: 1 })
  assert(await evaluate('!document.querySelector("dialog[open]")'), 'Backdrop closes drawer')
  await click('Create account')
  await fill('[aria-label="Account display name"]', 'Phone Person')
  await fill('[aria-label="Account job title"]', 'Analyst')
  await fill('[aria-label="Account display name"]', 'phoneperson')
  await fill('[aria-label="Account email"]', 'phoneperson@example.test')
  await fill('[aria-label="Account role"]', 'EMPLOYEE')
  assert(await evaluate('parseFloat(getComputedStyle(document.querySelector("select")).paddingRight) >= 36'))
  await fill('[aria-label="Account phone"]', '71')
  await evaluate(`document.querySelector('[aria-label="Account phone"]').focus(); document.querySelector('[aria-label="Account phone"]').blur()`)
  await waitText('Enter a valid number')
  assert(await evaluate('[...document.querySelectorAll("button")].find(b => b.textContent === "Confirm").disabled'))
  await fill('[aria-label="Account phone"]', '71123456')
  await fill('[aria-label="Phone country"]', 'US')
  assert(await evaluate('[...document.querySelectorAll("button")].find(b => b.textContent === "Confirm").disabled'))
  await fill('[aria-label="Account phone"]', '+44 20 7946 0018')
  assert.equal(await evaluate(`document.querySelector('[aria-label="Phone country"]').value`), 'GB')
  await fill('[aria-label="Account phone"]', '+961 71 123 456')
  for (const [width, height, scale, name] of [[900,900,1,'tablet'],[390,844,1,'mobile'],[1024,720,1.25,'zoom125-reflow'],[640,450,2,'zoom-reflow']]) {
    await viewport(width,height,scale)
    await fits()
    assert(await evaluate('document.querySelector(".form-drawer").getBoundingClientRect().right <= innerWidth + 1'))
    assert(await evaluate('getComputedStyle(document.querySelector(".form-drawer > form")).overflowY === "auto"'))
    assert(await evaluate('document.querySelector(".phone-code").textContent === "+961"'))
    if (height === 450) {
      await evaluate('document.querySelector(".form-drawer > form").scrollTop = 10000; void 0')
      assert(await evaluate('document.querySelector(".form-drawer > form").scrollTop > 0 && document.querySelector(".form-drawer").scrollTop === 0 && document.querySelector(".modal-header").getBoundingClientRect().top < 2'))
    }
    await screenshot(`drawer-${name}`)
  }
  await viewport(1440)
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: 'dark' }] })
  await delay(200)
  await screenshot('drawer-dark')
  await click('Confirm')
  await until(() => evaluate('!document.querySelector("dialog[open]")'), 'creation completed')
  const created = mutations.filter(m => m.path === '/auth/accounts').at(-1).body
  assert.equal(created.phoneNumber, '+96171123456')
  assert(!('country' in created))
  await until(() => evaluate('!!document.querySelector("[data-sonner-toast][data-type=success]")'), 'success toast semantics')
  const account = accounts.find(a => a.displayName === 'phoneperson')
  const openActions = () => evaluate(`document.querySelector('[data-account-id="${account.id}"] .action-menu-trigger').click()`)
  await openActions()
  await click('Edit account')
  await escape()
  assert(await evaluate(`document.activeElement === document.querySelector('[data-account-id="${account.id}"] .action-menu-trigger')`), 'Editing restores the visible action trigger')
  await openActions()
  await click('Edit account')
  assert.equal(await evaluate(`document.querySelector('[aria-label="Phone country"]').value`), 'LB')
  assert.equal((await evaluate(`document.querySelector('[aria-label="Account phone"]').value`)).replace(/\D/g,''), '71123456')
  await fill('[aria-label="Account phone"]', '')
  await click('Confirm')
  await until(() => evaluate('!document.querySelector("dialog[open]")'), 'edit completed')
  assert.equal(mutations.filter(m => m.path === `/users/${account.id}`).at(-1).body.phoneNumber, null)
  await openActions()
  failMailAction()
  await click('Resend activation')
  await waitText('Email service temporarily unavailable.')
  assert(await evaluate('!!document.querySelector("[data-sonner-toast][data-type=error] [data-icon]")'))
  await screenshot('error-toast-dark')
  await evaluate(`document.querySelector('[aria-label="Notifications"]').click()`)
  await waitText('No notifications yet')
  await screenshot('notifications-dark')
  await escape()
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: 'light' }] })
  await navigate('/admin/organization')
  await waitText('Regions, departments, specialties and team coverage.')
  delayCatalog(700)
  await click('Refresh organization')
  await waitText('Refreshing')
  assert(await evaluate('document.querySelector("h1").textContent === "Organization"'))
  await delay(900)
  delayCatalog(0)
  await viewport(320)
  await fits()
  assert(await evaluate('document.querySelector(".topbar-profile").getBoundingClientRect().right <= innerWidth'))
  await screenshot('topbar-mobile')
  await viewport(1440)
  assert.deepEqual(browserErrors, [])
  console.log('PASS: Kino branding, empty notifications, keyboard profile/back, Unicode initial/neutral avatar, Profile/Settings keyboard and mobile navigation, stable refresh, selects/toasts, drawer focus/Escape/backdrop/scroll, responsive dark mode, phone normalization/edit/clear')
}
