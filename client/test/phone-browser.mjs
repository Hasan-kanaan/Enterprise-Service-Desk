import assert from 'node:assert/strict'

export async function phoneBrowserChecks({ navigate, waitText, evaluate, fill, send, until }) {
  await navigate('/admin/accounts')
  await waitText('Employee Eve')
  await evaluate(`(() => {
    const row = document.querySelector('[data-account-id="3"]')
    row.querySelector('button[popovertarget]').click()
    ;[...row.querySelectorAll('button')].find(b => b.textContent === 'Edit account').click()
  })()`)
  await until(() => evaluate('!!document.querySelector(".phone-control input")'), 'phone field')
  const value = () => evaluate('document.querySelector(".phone-control input").value')
  const focusEnd = () => evaluate('(() => { const e = document.querySelector(".phone-control input"); e.focus(); e.setSelectionRange(e.value.length, e.value.length) })()')
  for (const [country, number] of [['LB', '71 123 456'], ['US', '(202) 555-0123'], ['CA', '(416) 555-0123'], ['GB', '020 7946 0018']]) {
    await fill('[aria-label="Account phone"]', '')
    await fill('[aria-label="Phone country"]', country)
    await fill('[aria-label="Account phone"]', number)
    await focusEnd()
    await send('Input.insertText', { text: '9' })
    assert.equal(await value(), number, `${country}: extra digit rejected`)
    for (const type of ['keyDown', 'keyUp']) await send('Input.dispatchKeyEvent', { type, key: 'Backspace', code: 'Backspace', windowsVirtualKeyCode: 8 })
    assert.equal(await value(), number.slice(0, -1))
    await send('Input.insertText', { text: number.at(-1) })
    assert.equal(await value(), number)
    await evaluate('document.querySelector(".phone-control input").setSelectionRange(0, 1)')
    await send('Input.insertText', { text: number[0] })
    assert.equal(await value(), number, 'selection replacement works at maximum')
    await focusEnd()
    await send('Input.insertText', { text: ' - ' })
    assert.equal(await value(), number + ' - ', 'formatting does not consume digit budget')
    await fill('[aria-label="Account phone"]', number + '999999')
    assert.equal(await value(), number + ' - ', 'overlong paste rejected without truncation')
  }
  await fill('[aria-label="Account phone"]', '')
  await fill('[aria-label="Phone country"]', 'LB')
  await fill('[aria-label="Account phone"]', '+44 20 7946 0018')
  assert.equal(await evaluate('document.querySelector(".phone-control select").value'), 'GB')
  assert.equal(await value(), '020 7946 0018')
  await fill('[aria-label="Phone country"]', 'LB')
  await focusEnd()
  await send('Input.insertText', { text: '9' })
  assert.equal(await value(), '020 7946 0018', 'changed country rejects further digits')
  await fill('[aria-label="Account phone"]', '71')
  await evaluate('document.querySelector(".phone-control input").blur()')
  assert.equal(await evaluate('document.querySelector(".phone-control input").getAttribute("aria-invalid")'), 'true')
  await fill('[aria-label="Account phone"]', '')
  assert.equal(await evaluate('document.querySelector(".phone-control input").getAttribute("aria-invalid")'), 'false')
  console.log('PASS: phone typing caps, deletion, selection replacement, paste, recognition, country changes and optional blank')
}
