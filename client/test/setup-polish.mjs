import assert from 'node:assert/strict'
import { setTimeout as delay } from 'node:timers/promises'

export async function setupPolishChecks({ navigate, click, fill, evaluate, waitText, until, send, requests, securityMail, delayNext, failNext, failDelivery, getSetupChecks }) {
  const count = () => requests.filter(r => r === 'POST /auth/setup').length
  const disabled = () => evaluate('document.querySelector("button[type=submit]").disabled')
  const toggle = () => evaluate('document.querySelector(".setup-restart").click()')
  const complete = () => until(() => evaluate('document.querySelector("form").getAttribute("aria-busy") === "false"'), 'submission settled')
  const firstIdentity = { displayName: 'Root Operator', jobTitle: 'Administrator', email: 'typo@example.test' }
  await navigate('/login')
  await waitText('Create the root administrator.')
  assert.equal(await evaluate('location.pathname'), '/setup')
  assert(!/Welcome back|Forgot password/.test(await evaluate('document.body.innerText')))
  assert.equal(await disabled(), false, 'first submission enabled without restart')
  assert.equal(await evaluate('document.querySelector("input[name=restart]").checked'), false)
  assert.equal(await evaluate('!!document.querySelector("input[name=password]")'), false)
  const checks = getSetupChecks()
  await delay(700)
  assert.equal(getSetupChecks(), checks, 'no setup redirect loop')
  assert.equal(await evaluate('!!document.querySelector(".public-auth-navigation a")'), false)
  for (const [name, value] of Object.entries({ ...firstIdentity, setupSecret: 'wrong' })) await fill(`input[name="${name}"]`, value)
  await click('Send activation email')
  await waitText('Invalid setup credentials')
  await complete()
  await fill('input[name="setupSecret"]', 'fixture-installation-secret')
  delayNext()
  const before = count()
  await click('Send activation email')
  assert(await evaluate('document.querySelector("fieldset").disabled'))
  await evaluate('document.querySelector("form").requestSubmit()')
  await waitText('Activation email sent.')
  await complete()
  assert.equal(count(), before + 1)
  assert(await evaluate('!!document.querySelector("[data-sonner-toast][data-type=success]")'))
  assert((await evaluate('document.querySelector(".setup-delivery").innerText')).includes('verify your address and choose your password. Then sign in.'))
  assert.equal(await evaluate('location.pathname'), '/setup')
  const stored = await evaluate('JSON.stringify(localStorage) + JSON.stringify(sessionStorage)')
  for (const sensitive of ['fixture-installation-secret', ...Object.values(firstIdentity)]) assert(!stored.includes(sensitive))
  const oldToken = securityMail.at(-1).token
  assert(await disabled(), 'successful first send cannot repeat')
  await toggle()
  assert(await disabled(), 'confirmation alone cannot repeat unchanged identity')
  for (const [name, value] of Object.entries({ displayName: '  Root Operator  ', jobTitle: ' Administrator ', email: 'TYPO@EXAMPLE.TEST', setupSecret: 'different-secret' })) {
    await fill(`input[name="${name}"]`, value)
    assert(await disabled(), 'normalization/secret changes do not count')
  }
  for (const [name, value] of Object.entries({ ...firstIdentity, setupSecret: 'fixture-installation-secret' })) await fill(`input[name="${name}"]`, value)
  for (const field of ['displayName', 'jobTitle', 'email']) {
    await fill(`input[name="${field}"]`, field === 'email' ? 'corrected@example.test' : 'Corrected value')
    assert.equal(await disabled(), false, `${field} is restart editable`)
    await fill(`input[name="${field}"]`, firstIdentity[field])
    assert(await disabled())
  }
  await toggle()
  await fill('input[name="email"]', 'corrected@example.test')
  assert(await disabled(), 'changed identity also needs explicit confirmation')
  const blockedCount = count()
  await evaluate('document.querySelector("form").requestSubmit()')
  await complete()
  assert.equal(count(), blockedCount, 'submit handler also guards the request')
  await evaluate('document.querySelector("input[name=restart]").focus()')
  await send('Input.dispatchKeyEvent', { type: 'keyDown', key: ' ', code: 'Space', windowsVirtualKeyCode: 32 })
  await send('Input.dispatchKeyEvent', { type: 'keyUp', key: ' ', code: 'Space', windowsVirtualKeyCode: 32 })
  assert.equal(await evaluate('document.querySelector("input[name=restart]").checked'), true, 'native keyboard selection')
  assert.equal(await evaluate('document.querySelector(".setup-restart").dataset.selected'), 'true')
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".setup-restart")).outlineStyle'), 'solid')
  assert.equal(await disabled(), false)
  failNext([409, { message: 'Setup could not be started. Check installation state and details.' }])
  await click('Restart setup and send activation')
  await waitText('Setup could not be started.')
  await complete()
  assert.equal(await disabled(), false, 'backend rejection can be retried')
  assert.equal(securityMail.find(m => m.token === oldToken).used, false, 'failed correction does not invalidate the old link')
  failDelivery()
  delayNext()
  await click('Restart setup and send activation')
  assert(await evaluate('document.querySelector("fieldset").disabled'))
  await evaluate('document.querySelector("form").requestSubmit()')
  await waitText('Activation email could not be delivered.')
  await complete()
  assert.equal(count(), blockedCount + 2, 'one failed request and one delivery-failed correction')
  assert(await evaluate('!!document.querySelector("[data-sonner-toast][data-type=error]")'))
  assert.equal(securityMail.find(m => m.token === oldToken).used, true, 'committed restart invalidates old links even on SMTP failure')
  assert.equal(await evaluate('document.querySelector(".setup-delivery a").getAttribute("href")'), '/resend-activation')
  await toggle()
  assert(await disabled(), 'FAILED delivery still establishes the saved baseline')
  assert((await evaluate('document.querySelector(".setup-delivery").innerText')).includes('pending identity was saved'))
  await click('Request another activation email')
  await waitText('For a provisioned account you have not activated yet')

  // Reload boundaries are deliberately truthful: status returns availability only.
  await navigate('/setup')
  await waitText('Create the root administrator.')
  assert.equal(await evaluate('document.querySelector("input[name=email]").value'), '')
  assert.equal(await evaluate('document.querySelector("input[name=setupSecret]").value'), '')
  assert.equal(await disabled(), false)
  await waitText('After a reload, saved pending details are not available here')
  for (const [name, value] of Object.entries({ ...firstIdentity, email: 'corrected@example.test', setupSecret: 'fixture-installation-secret' })) await fill(`input[name="${name}"]`, value)
  await click('Send activation email')
  await waitText('Setup could not be started.')
  await complete()
  await toggle()
  await click('Restart setup and send activation')
  await waitText('Activation email sent.')
  await complete()
  assert(await disabled())
  await send('Emulation.setDeviceMetricsOverride', { width: 320, height: 740, deviceScaleFactor: 1, mobile: true })
  for (const scheme of ['light', 'dark']) {
    await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: scheme }] })
    // Batch 5A applies live system changes through the MediaQueryList event.
    await until(() => evaluate(`document.documentElement.dataset.theme === '${scheme}' && getComputedStyle(document.documentElement).colorScheme === '${scheme}'`), `${scheme} setup theme`)
    assert.equal(await evaluate('getComputedStyle(document.documentElement).colorScheme'), scheme)
    assert(await evaluate('document.documentElement.scrollWidth <= innerWidth'), `${scheme} mobile overflow`)
    assert(await evaluate('document.querySelector(".setup-restart").getBoundingClientRect().width <= innerWidth'))
    assert(await evaluate('document.querySelector("button[type=submit]").getBoundingClientRect().height >= 44'))
  }
  assert(!(await evaluate('document.body.innerText')).includes('Return to sign in'))
  await navigate('/login')
  await waitText('Create the root administrator.') // Login still routes back while pending.
  await send('Emulation.setEmulatedMedia', { features: [] })
  console.log('PASS: setup confirmation, normalized identity guards, duplicate-submit prevention, delivery toasts, failure recovery, secret storage, reload boundary, keyboard, mobile and dark mode')
}
