import assert from 'node:assert/strict'

export async function shellProfileChecks({ send, navigate, evaluate, click, waitText, until, setUser, setSession }) {
  const icon = async label => {
    await until(() => evaluate(`!!document.querySelector('[aria-label="${label}"]')`), label)
    await evaluate(`document.querySelector('[aria-label="${label}"]').click()`)
  }
  const system = value => send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value }] })
  const theme = value => until(() => evaluate(`document.documentElement.dataset.theme === '${value}' && getComputedStyle(document.documentElement).colorScheme === '${value}'`), `${value} theme`)
  const fits = () => evaluate('document.documentElement.scrollWidth <= innerWidth')
  const key = async (key, code, windowsVirtualKeyCode) => {
    for (const type of ['keyDown', 'keyUp']) await send('Input.dispatchKeyEvent', { type, key, code, windowsVirtualKeyCode, ...(type === 'keyDown' && key === 'Enter' ? { text: '\r' } : {}) })
  }
  await navigate('/profile')
  await waitText('Change password')
  await evaluate('localStorage.removeItem("kino-theme")')
  await system('dark')
  await navigate('/settings')
  await waitText('Change password')
  await theme('dark')
  assert.equal(await evaluate('location.pathname'), '/profile')
  assert.equal(await evaluate('document.querySelector("h1").textContent'), 'Account settings')
  await waitText('Your sessions')
  assert(await evaluate('!!document.querySelector("input[autocomplete=current-password]")'))
  assert(!(await evaluate('document.querySelector("main").innerText')).includes('coming soon'))
  await system('light')
  await theme('light')
  const lightScrollbar = await evaluate('getComputedStyle(document.documentElement, "::-webkit-scrollbar-thumb").backgroundColor')
  const saved = await evaluate('JSON.stringify(localStorage)')
  await evaluate('window.shellMarker = "same-page"')
  await icon('Switch to dark theme')
  await theme('dark')
  assert.notEqual(await evaluate('getComputedStyle(document.documentElement, "::-webkit-scrollbar-thumb").backgroundColor'), lightScrollbar)
  assert.equal(await evaluate('getComputedStyle(document.documentElement, "::-webkit-scrollbar").width'), '12px')
  assert.equal(await evaluate('window.shellMarker'), 'same-page')
  assert.equal(await evaluate('location.pathname'), '/profile')
  assert.equal(await evaluate('localStorage.getItem("kino-theme")'), 'dark')
  assert.deepEqual(await evaluate('Object.fromEntries(Object.entries(localStorage).filter(([key]) => key !== "kino-theme"))'), JSON.parse(saved))
  assert.equal(await evaluate('document.querySelectorAll("[data-sonner-toast]").length'), 0)
  await navigate('/profile')
  await waitText('Change password')
  await theme('dark')
  await system('dark')
  await icon('Switch to light theme')
  await theme('light')
  await navigate('/profile')
  await waitText('Change password')
  await theme('light')
  await system('light'); await system('dark')
  await theme('light')
  // Cross-tab preference removal is delivered by the browser as a storage event.
  await evaluate('localStorage.removeItem("kino-theme"); window.dispatchEvent(new StorageEvent("storage", {key:"kino-theme", newValue:null, storageArea:localStorage}))')
  await theme('dark')
  await system('light'); await theme('light')
  await evaluate('localStorage.setItem("kino-theme", "invalid")')
  await system('dark')
  await navigate('/profile'); await waitText('Change password'); await theme('dark')
  await evaluate('localStorage.removeItem("kino-theme")')

  await navigate('/admin'); await waitText('Administration')
  assert.deepEqual(await evaluate('[...document.querySelector(".topbar-account").children].map(el => el.getAttribute("aria-label"))'), ['Notifications', 'Switch to light theme', 'Account settings'])
  assert.equal(await evaluate('document.querySelector(".topbar-account").innerText.trim()'), '')
  assert.equal(await evaluate('document.querySelector(".sidebar-account strong").textContent'), 'Admin user')
  assert.equal(await evaluate('document.querySelector(".sidebar-account .avatar").textContent'), 'A')
  assert(await evaluate('!!document.querySelector(".sidebar-account button.sign-out")'))
  await evaluate('document.querySelector("[aria-label=Notifications]").focus()')
  await key('Tab', 'Tab', 9)
  assert.equal(await evaluate('document.activeElement.getAttribute("aria-label")'), 'Switch to light theme')
  await key('Tab', 'Tab', 9)
  assert.equal(await evaluate('document.activeElement.getAttribute("aria-label")'), 'Account settings')
  assert.equal(await evaluate('getComputedStyle(document.activeElement).outlineStyle'), 'solid')
  await key('Enter', 'Enter', 13)
  await waitText('Change password')
  await click('Back')
  await until(() => evaluate('location.pathname === "/admin"'), 'back to originating page')
  await evaluate('history.forward()')
  await waitText('Change password')
  await icon('Notifications')
  await waitText('No notifications yet')
  assert(await evaluate('getComputedStyle(document.querySelector("dialog")).backgroundColor !== "rgb(255, 255, 255)"'))
  await key('Escape','Escape',27)

  for (const role of ['EMPLOYEE', 'AGENT', 'MANAGER', 'ADMIN', 'SUPER_ADMIN']) {
    setUser({ role, displayName: 'Long Display Name '.repeat(12) })
    await navigate('/settings')
    await waitText('Change password')
    assert.equal(await evaluate('location.pathname'), '/profile')
    for (const width of [1440, 768, 320]) {
      await send('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: width < 600 })
      assert(await fits(), `${role} ${width}px fits`)
      assert(await evaluate('[...document.querySelector(".topbar-account").children].every(el => { const r=el.getBoundingClientRect(); return r.width>=44 && r.height>=44 && r.right<=innerWidth })'))
      if (width < 1024) {
        await icon('Open navigation')
        await until(() => evaluate('!!document.querySelector("dialog.navigation-drawer[open]")'), 'drawer open')
        assert(await evaluate('document.querySelector(".navigation-drawer .account-identity strong").scrollWidth > document.querySelector(".navigation-drawer .account-identity strong").clientWidth'), 'long identity truncates')
        await evaluate('document.querySelector(".navigation-drawer .account-link").click()')
        await until(() => evaluate('!document.querySelector("dialog.navigation-drawer[open]")'), 'account navigation closes drawer')
        assert.equal(await evaluate('location.pathname'), '/profile')
      }
    }
  }
  setUser({ role:'ADMIN', displayName:'  ' })
  await navigate('/profile'); await waitText('Change password')
  assert.equal(await evaluate('document.querySelector(".sidebar-account strong").textContent'), 'Account')
  assert.equal(await evaluate('document.querySelector(".sidebar-account .avatar").textContent'), 'A')
  // Explicit theme also controls Tailwind public surfaces, not just CSS variables.
  await icon('Switch to light theme')
  setSession(false)
  await navigate('/login'); await waitText('Welcome back')
  await theme('light')
  const lightBackground = await evaluate('getComputedStyle(document.querySelector("main")).backgroundImage')
  await evaluate('localStorage.setItem("kino-theme", "dark")')
  await navigate('/login'); await waitText('Welcome back'); await theme('dark')
  assert.notEqual(await evaluate('getComputedStyle(document.querySelector("main")).backgroundImage'), lightBackground)
  await evaluate('localStorage.removeItem("kino-theme")')
  setSession(false)
  await navigate('/settings'); await waitText('Welcome back')
  assert.equal(await evaluate('location.pathname'), '/login', 'alternate route remains protected')
  await send('Emulation.setEmulatedMedia', { features: [] })
  console.log('PASS: canonical account routing, all-role shell, identity fallback/truncation, notifications, keyboard/back/forward, system/explicit/persisted themes, public theme and desktop/tablet/mobile')
}
